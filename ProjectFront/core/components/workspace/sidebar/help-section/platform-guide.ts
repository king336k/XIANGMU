export function findGuideTopics(query: string) {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return platformGuide.filter((topic) =>
    words.every((word) =>
      [topic.title, topic.summary, ...topic.paragraphs, ...topic.steps].join(" ").toLocaleLowerCase().includes(word)
    )
  );
}
