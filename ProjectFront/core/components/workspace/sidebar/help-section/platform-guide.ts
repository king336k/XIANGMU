export function findGuideTopics(query: string, section: GuideSection = "all") {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return platformGuide.filter(
    (topic) =>
      (section === "all" || topic.section === section) &&
      words.every((word) =>
        [
          topic.title,
          topic.summary,
          ...topic.keywords,
          ...topic.paragraphs,
          ...topic.steps,
          ...topic.checkpoints,
          ...topic.screenshots.flatMap((image) => [image.title, image.caption]),
        ]
          .join(" ")
          .toLocaleLowerCase()
          .includes(word)
      )
  );
}
